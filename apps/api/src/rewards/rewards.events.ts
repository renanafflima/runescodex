const SUPPORTED = new Set<string>(Object.values(REWARD_EVENTS));

export function isSupportedRewardEvent(
  eventType: string,
): eventType is RewardEventType {
  return SUPPORTED.has(eventType);
}

export function isImplementedRewardEvent(eventType: string): boolean {
  return IMPLEMENTED_REWARD_EVENTS.has(eventType);
}